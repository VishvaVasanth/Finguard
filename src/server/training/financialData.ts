/**
 * Generates side-by-side comparison between two companies
 */
export function compareCompanies(comp1Id: string, comp2Id: string, year: string = '2024'): TableSummary {
  const c1 = COMPANY_FINANCIAL_DATABASE[comp1Id] || COMPANY_FINANCIAL_DATABASE.AAPL;
  const c2 = COMPANY_FINANCIAL_DATABASE[comp2Id] || COMPANY_FINANCIAL_DATABASE.MSFT;

  const y1 = c1.years[year] || c1.years['2024'];
  const y2 = c2.years[year] || c2.years['2024'];

  const headers = ['Financial Line Item (Audited 10-K)', `${c1.name} (FY${year})`, `${c2.name} (FY${year})`, 'Comparison / Delta'];
  const rows = [
    [
      'Consolidated Revenue',
      `${c1.currency}${y1.revenue} ${c1.unit}`,
      `${c2.currency}${y2.revenue} ${c2.unit}`,
      c1.currency === c2.currency
        ? `${y1.revenue > y2.revenue ? c1.name : c2.name} leads by ${c1.currency}${Math.abs(y1.revenue - y2.revenue).toFixed(2)} ${c1.unit}`
        : 'Different reporting currencies',
    ],
    [
      'Operating Income (EBIT)',
      `${c1.currency}${y1.operating_income} ${c1.unit}`,
      `${c2.currency}${y2.operating_income} ${c2.unit}`,
      c1.currency === c2.currency
        ? `${y1.operating_income > y2.operating_income ? c1.name : c2.name} leads by ${c1.currency}${Math.abs(y1.operating_income - y2.operating_income).toFixed(2)} ${c1.unit}`
        : 'Different reporting currencies',
    ],
    [
      'Operating Margin (%)',
      `${y1.operating_margin}%`,
      `${y2.operating_margin}%`,
      `${y1.operating_margin > y2.operating_margin ? c1.name : c2.name} higher by ${(Math.abs(y1.operating_margin - y2.operating_margin)).toFixed(2)}% pts`,
    ],
    [
      'Consolidated Net Income',
      `${c1.currency}${y1.net_income} ${c1.unit}`,
      `${c2.currency}${y2.net_income} ${c2.unit}`,
      c1.currency === c2.currency
        ? `${y1.net_income > y2.net_income ? c1.name : c2.name} leads by ${c1.currency}${Math.abs(y1.net_income - y2.net_income).toFixed(2)} ${c1.unit}`
        : 'Different reporting currencies',
    ],
    [
      'Net Profit Margin (%)',
      `${y1.net_margin}%`,
      `${y2.net_margin}%`,
      `${y1.net_margin > y2.net_margin ? c1.name : c2.name} higher by ${(Math.abs(y1.net_margin - y2.net_margin)).toFixed(2)}% pts`,
    ],
    [
      'Diluted EPS',
      `${c1.currency}${y1.eps_diluted}`,
      `${c2.currency}${y2.eps_diluted}`,
      'Per share basis',
    ],
    [
      'Free Cash Flow (FCF)',
      `${c1.currency}${y1.free_cash_flow} ${c1.unit}`,
      `${c2.currency}${y2.free_cash_flow} ${c2.unit}`,
      c1.currency === c2.currency
        ? `${y1.free_cash_flow > y2.free_cash_flow ? c1.name : c2.name} higher by ${c1.currency}${Math.abs(y1.free_cash_flow - y2.free_cash_flow).toFixed(2)} ${c1.unit}`
        : 'Operating Cash Flow minus CapEx',
    ],
  ];

  return { headers, rows };
}

