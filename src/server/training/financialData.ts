export const AUDITED_FINANCIAL_YEARS = COMPANY_FINANCIAL_DATABASE.FINGUARD.years;

/**
 * Detects company mentioned in query
 */
export function detectCompanyFromQuery(query: string): CompanyProfile {
  const q = query.toLowerCase();

  for (const comp of Object.values(COMPANY_FINANCIAL_DATABASE)) {
    if (comp.aliases.some((alias) => q.includes(alias.toLowerCase()))) {
      return comp;
    }
  }

  // If no company name is matched, default to FinGuard Corporation
  return COMPANY_FINANCIAL_DATABASE.FINGUARD;
}

/**
 * Detects if two companies are being compared in the same query
 */
export function detectComparisonCompanies(query: string): { comp1: CompanyProfile; comp2: CompanyProfile } | null {
  const q = query.toLowerCase();
  const matched: CompanyProfile[] = [];

  for (const comp of Object.values(COMPANY_FINANCIAL_DATABASE)) {
    if (comp.aliases.some((alias) => q.includes(alias.toLowerCase()))) {
      if (!matched.some((m) => m.id === comp.id)) {
        matched.push(comp);
      }
    }
  }

  if (matched.length >= 2) {
    return { comp1: matched[0], comp2: matched[1] };
  }

  return null;
}

